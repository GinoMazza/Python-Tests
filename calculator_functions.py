def sumar(a, b):
    return a + b


def restar(a, b):
    return a - b


def multiplicar(a, b):
    return a * b


def dividir(a, b):
    return a / b


print("----- PYTHON CALCULATOR -----")
print("El resultado es:", sumar(10, 5))
print("El resultado es:", restar(10, 5))
print("El resultado es:", multiplicar(10, 5))
print("El resultado es:", dividir(10, 5))
